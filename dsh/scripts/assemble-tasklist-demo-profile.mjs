#!/usr/bin/env node
/**
 * Live-verification scaffolding for `@lmthing/dsh-space-tasklist` — a SEPARATE
 * script from `assemble-lmthing-profile.mjs` on purpose (that one owns the
 * shared `lmthing`/`lmthing-web` profiles; this one owns nothing but its own
 * `tasklist-demo` profile and the `system-tasklist-demo` toy space).
 *
 * Regenerates `$DSH_HOME/profiles/tasklist-demo/cordis.patch.yml`, which:
 *   1. sets the demo planner's persona on the GLOBAL `system-prompt.persona`
 *      config — the same unavoidable workaround the shared script uses while
 *      this port has no `dsh-agent-presets` roster (see @lmthing/dsh-space's
 *      doc comment for exactly why `dsh-persona` can't be mounted unscoped).
 *   2. mounts `@lmthing/dsh-space-tasklist` directly as its own row. It is
 *      deliberately NOT added to the `@lmthing/dsh-space` umbrella here —
 *      composing it there is a separate, sequential integration step.
 *
 * `ctx.workflowEngine` needs no extra row: `@deepseek-ai/dsh-base`'s own
 * default patch already mounts `@deepseek-ai/dsh-workflow-worker-thread`
 * (`id: workflow-worker-thread`, `provider: spawn`).
 *
 * Usage: node dsh/scripts/assemble-tasklist-demo-profile.mjs [profileName] [dshHome]
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { loadSpace } from '@lmthing/dsh-space-format'
import { resolvePersonaText } from '@lmthing/dsh-space-persona'
// By relative path, not by package name: `@lmthing/dsh-space-tasklist` is not
// (yet) a devDependency of dsh/package.json, so it isn't linked into
// dsh/node_modules — that row belongs to the sequential integration step that
// also adds it to the @lmthing/dsh-space umbrella.
import { resolveTasklistTools } from '../packages/space-tasklist/src/resolve.js'

const here = dirname(fileURLToPath(import.meta.url))
const dshDir = join(here, '..')
const demoDir = join(dshDir, 'system-spaces', 'system-tasklist-demo')

const profileName = process.argv[2] ?? 'tasklist-demo'
const dshHome = process.argv[3] ?? join(dshDir, '.dsh-home')
const profileDir = join(dshHome, 'profiles', profileName)

const space = await loadSpace(demoDir)
const planner = space.agents.planner
if (!planner) throw new Error(`expected a "planner" agent in ${demoDir}`)

const personaText = await resolvePersonaText(demoDir, 'planner')
const tools = await resolveTasklistTools(demoDir, 'planner')

await mkdir(profileDir, { recursive: true })

await writeFile(
  join(profileDir, 'cordis.yml'),
  '# dsh profile root — an empty entry list; the tree is composed as patches.\n[]\n',
  'utf8',
)

await writeFile(
  join(profileDir, 'pnpm-workspace.yaml'),
  'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n',
  'utf8',
)

await writeFile(
  join(profileDir, 'package.json'),
  `${JSON.stringify(
    {
      name: `dsh-profile-${profileName}`,
      private: true,
      dependencies: {
        '@deepseek-ai/dsh-headless': '0.1.1-rc.2',
        '@lmthing/dsh-llm-mock': `link:${join(dshDir, 'packages', 'llm-mock')}`,
        '@lmthing/dsh-space-tasklist': `link:${join(dshDir, 'packages', 'space-tasklist')}`,
      },
      dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless'] } },
    },
    null,
    2,
  )}\n`,
  'utf8',
)

const patch = [
  // Keyless by default; override with a --patch overlay for a real provider.
  { id: 'agent-default-model', config: { provider: 'lmthing-mock', model: 'mock-1' } },
  // ENOSPC workaround — see dsh/packages/README.md.
  { id: 'skill-filesystem', config: { watch: false } },
  { id: 'settings', config: { watch: false } },
  { id: 'credentials', config: { watch: false } },
  { id: 'system-prompt', config: { persona: personaText } },
  {
    insert: [
      { id: 'lmthing-llm-mock', name: '@lmthing/dsh-llm-mock' },
      {
        id: 'planner-tasklists',
        name: '@lmthing/dsh-space-tasklist',
        config: { spaceDir: demoDir, agentSlug: 'planner' },
      },
    ],
  },
]

const header = '# GENERATED by dsh/scripts/assemble-tasklist-demo-profile.mjs — re-run it to regenerate.\n'
await writeFile(join(profileDir, 'cordis.patch.yml'), header + stringify(patch), 'utf8')

console.log(`wrote ${join(profileDir, 'cordis.patch.yml')}`)
console.log(`tasklist tools: ${tools.map((t) => t.toolName).join(', ') || '(none)'}`)
for (const tool of tools) {
  console.log(`  ${tool.toolName} -> tasklist "${tool.tasklist}", meta "${tool.meta.name}", ${tool.script.split('\n').length} script lines`)
}
console.log(`next: (cd ${profileDir} && pnpm install) then DSH_HOME=${dshHome} npx dsh --profile ${profileName} "<message>"`)
