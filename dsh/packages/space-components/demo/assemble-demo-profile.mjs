#!/usr/bin/env node
/**
 * Live-verification harness for `@lmthing/dsh-space-components` — the local
 * counterpart to `dsh/scripts/assemble-lmthing-profile.mjs`, kept here instead
 * of extending that shared script so this verification touches no file another
 * feature plugin is editing in parallel.
 *
 * Regenerates `$DSH_HOME/profiles/components-demo/cordis.patch.yml`, mounting
 * `@lmthing/dsh-space-components` DIRECTLY (the umbrella `@lmthing/dsh-space`
 * plugin does not compose it yet — that integration is a separate, sequential
 * step) against `dsh/system-spaces/system-components-demo`.
 *
 * Usage: node demo/assemble-demo-profile.mjs [agentSlug] [profileName] [dshHome]
 *   agentSlug   `curator` (declares components: [EchoCard]) or `plain`
 *               (declares none — the negative case). Default: curator.
 *   profileName default: components-demo
 */
import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { loadSpace } from '@lmthing/dsh-space-format'

const here = dirname(fileURLToPath(import.meta.url))
const packageDir = join(here, '..')
const dshDir = join(packageDir, '../..')
const spaceDir = join(dshDir, 'system-spaces/system-components-demo')

const agentSlug = process.argv[2] ?? 'curator'
const profileName = process.argv[3] ?? 'components-demo'
const dshHome = process.argv[4] ?? join(dshDir, '.dsh-home')
const patchFile = join(dshHome, 'profiles', profileName, 'cordis.patch.yml')

const space = await loadSpace(spaceDir)
const agent = space.agents[agentSlug]
if (!agent) {
  throw new Error(`expected a "${agentSlug}" agent in ${spaceDir} (have: ${Object.keys(space.agents).join(', ')})`)
}

// The one ambient agent's persona, set globally — same constraint as the
// lmthing profile (no dsh-agent-presets roster yet, so dsh-persona cannot be
// mounted unscoped; see packages/space/src/index.js's doc comment).
const persona = [agent.charterBody, agent.instructBody].filter(Boolean).join('\n\n').trim()

const patch = [
  { id: 'agent-default-model', config: { provider: 'components-demo-mock', model: 'mock-1' } },
  // ENOSPC workaround — see dsh/packages/README.md.
  { id: 'skill-filesystem', config: { watch: false } },
  { id: 'settings', config: { watch: false } },
  { id: 'credentials', config: { watch: false } },
  { id: 'system-prompt', config: { persona } },
  {
    insert: [
      {
        // Mounted by SUBPATH out of this same package — see display-mock.js's
        // doc comment for why it is not a separate linked package.
        id: 'components-demo-mock',
        name: '@lmthing/dsh-space-components/demo/display-mock.js',
      },
      {
        id: 'components-demo-space',
        name: '@lmthing/dsh-space-components',
        config: { spaceDir, agentSlug },
      },
    ],
  },
]

const header = `# GENERATED by dsh/packages/space-components/demo/assemble-demo-profile.mjs — re-run it to regenerate.\n# Do not hand-edit. Live-verification harness only; see the package README.\n\n`
await writeFile(patchFile, header + stringify(patch), 'utf8')
console.log(`wrote ${patchFile}`)
console.log(`agent: ${agentSlug} — components: ${agent.config.components.join(', ') || '(none)'}`)
