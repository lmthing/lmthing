/**
 * Materializes the `lmthing-web` dsh profile under a (possibly brand-new,
 * PVC-backed) `$DSH_HOME` on every boot — Part B1, see dsh/PROGRESS.md.
 *
 * Two things must exist before `dsh --profile lmthing-web` can boot, and
 * neither survives a fresh PVC:
 *   1. `$DSH_HOME/profiles/lmthing-web/package.json` — previously a hand-
 *      crafted, gitignored LOCAL dev file (Part A3's fix: list only
 *      `@lmthing/*` link deps, never `@deepseek-ai/dsh-web-app` directly, or
 *      the host plane resolves a duplicate module identity — see
 *      assemble-lmthing-profile.mjs's own doc comment). In production there
 *      is no repo checkout to hand-edit a file into, so this module writes it
 *      fresh against wherever this image placed the `@lmthing/dsh-*`
 *      packages.
 *   2. `$DSH_HOME/profiles/lmthing-web/cordis.patch.yml` + the
 *      `$DSH_HOME/.agent-presets/` roster — generated by
 *      `assemble-lmthing-profile.mjs`, which is safe to re-run every boot
 *      (its own header: "regenerate, don't hand-edit").
 *
 * Model routing: `@deepseek-ai/dsh-llm-pi-ai` ships mounted-but-dormant in
 * `dsh-base` (confirmed by reading its `cordis.patch.yml`: zero routes until a
 * `providers` config exists) — so pointing it at LiteLLM is a plain top-level
 * PATCH, not a new plugin insert. The gateway already injects
 * `LMTHINGCLOUD_BASE_URL`/`LMTHINGCLOUD_API_KEY` into every pod's env
 * (`cloud/gateway/src/lib/compute.ts#litellmEnvDefaults`) — `apiKeyEnv` below
 * names that variable; the secret value itself never touches a file on disk.
 * Applied as a second `--patch` layered on top of the assembled profile
 * (same mechanism `run-web.sh --real` already uses for its own overlay), so
 * it overrides the profile's keyless tracer-bullet `agent-default-model`
 * without assemble-lmthing-profile.mjs needing to know about production at
 * all.
 */
import { access, mkdir, writeFile } from 'node:fs/promises'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { join } from 'node:path'
import { stringify } from 'yaml'

const execFileAsync = promisify(execFile)

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

/**
 * @param {object} opts
 * @param {string} opts.dshRoot - the dsh workspace root baked into this image.
 * @param {string} opts.dshHome - the persistent (PVC-backed) DSH_HOME.
 * @param {string} [opts.model] - LiteLLM model id; defaults to the fleet default (LM_MODEL_M's target).
 */
export async function bootstrapProfile({ dshRoot, dshHome, model = 'DeepSeek-V4-Flash-0731' }) {
  const profileDir = join(dshHome, 'profiles', 'lmthing-web')
  await mkdir(profileDir, { recursive: true })

  const packageJsonPath = join(profileDir, 'package.json')
  const isFreshProfile = !(await exists(packageJsonPath))
  if (isFreshProfile) {
    const linkDep = (pkg) => `link:${join(dshRoot, 'packages', pkg)}`
    await writeFile(
      packageJsonPath,
      JSON.stringify(
        {
          name: 'dsh-profile-lmthing-web',
          private: true,
          // Only @lmthing/* link deps — see the module doc comment (Part A3): a
          // direct @deepseek-ai/dsh-web-app dep here creates a duplicate host-plane
          // module identity and every tool call fails with "Cannot read properties
          // of undefined (reading 'prepare')". @lmthing/dsh-llm-mock stays listed even
          // in production: assemble-lmthing-profile.mjs inserts it unconditionally
          // (it is a harmless, unused mounted provider once agent-default-model is
          // patched elsewhere below) — cheaper than teaching that script about a
          // production mode it otherwise has no reason to know about.
          dependencies: {
            '@lmthing/dsh-llm-mock': linkDep('llm-mock'),
            '@lmthing/dsh-space': linkDep('space'),
            '@lmthing/dsh-subagent-preset': linkDep('subagent-preset'),
            '@lmthing/dsh-client-space-components': linkDep('client-space-components'),
          },
          dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app'] } },
        },
        null,
        2,
      ),
      'utf8',
    )
    // A dsh profile is its own tiny pnpm project (isolated from the dsh/ repo
    // workspace it links back into) — mirrors exactly what `dsh profile new`
    // itself generates (confirmed against the hand-bootstrapped local dev
    // profile). `hoisted` avoids pnpm's symlinked strict node_modules inside
    // what is, at runtime, an ephemeral generated directory, not a real package.
    await writeFile(join(profileDir, 'cordis.yml'), '# dsh profile root — patches (bundles, then cordis.patch.yml, then --patch overlays) do the real composing.\n[]\n', 'utf8')
    await writeFile(join(profileDir, 'pnpm-workspace.yaml'), 'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n', 'utf8')
    await execFileAsync('pnpm', ['install'], { cwd: profileDir })
  }

  await execFileAsync(process.execPath, [join(dshRoot, 'scripts', 'assemble-lmthing-profile.mjs'), 'lmthing-web', dshHome], {
    cwd: dshRoot,
  })

  const patchPaths = []
  if (process.env.LMTHINGCLOUD_BASE_URL) {
    const prodPatchPath = join(dshHome, 'prod-provider.patch.yml')
    const patch = [
      {
        id: 'llm-pi-ai',
        config: {
          providers: {
            lmthingcloud: {
              baseURL: process.env.LMTHINGCLOUD_BASE_URL,
              // Confirmed live: dsh-llm-pi-ai's `api` is a closed enum —
              // "openai-completions" | "openai-responses" | "anthropic-messages"
              // — "openai" alone is rejected by cordis config validation.
              // LiteLLM's /v1 is the OpenAI Chat Completions wire shape.
              api: 'openai-completions',
              apiKeyEnv: 'LMTHINGCLOUD_API_KEY',
              models: [{ id: model }],
            },
          },
        },
      },
      { id: 'agent-default-model', config: { provider: 'lmthingcloud', model } },
    ]
    await writeFile(
      prodPatchPath,
      `# GENERATED by @lmthing/dsh-pod-server on every boot — do not hand-edit.\n\n${stringify(patch)}`,
      'utf8',
    )
    patchPaths.push(prodPatchPath)
  }

  return { profileDir, patchPaths }
}
