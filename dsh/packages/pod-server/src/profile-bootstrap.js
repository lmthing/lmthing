/**
 * Materializes the `lmthing-web` dsh profile under a (possibly brand-new,
 * `emptyDir`-backed) `$DSH_HOME` on every boot — Part B1, see dsh/PROGRESS.md.
 *
 * Two things must exist before `dsh --profile lmthing-web` can boot, and
 * neither survives a fresh `emptyDir`:
 *   1. `$DSH_HOME/profiles/lmthing-web/package.json` (+ its `node_modules`) —
 *      previously a hand-crafted, gitignored LOCAL dev file (Part A3's fix:
 *      list only `@lmthing/*` link deps, never `@deepseek-ai/dsh-web-app`
 *      directly, or the host plane resolves a duplicate module identity —
 *      see lmthing-web-profile-manifest.mjs's own doc comment). This
 *      profile's shape is 100% static (same for every user, every boot), so
 *      `devops/argocd/compute/Dockerfile.dsh` bakes it — `pnpm install`
 *      included — into the image at `<dshRoot>/.profile-base/lmthing-web`
 *      at build time. Materializing it here is then just a fast local copy,
 *      not a network-dependent `pnpm install` on every single pod restart
 *      (`lmthing-dsh`'s volume is `emptyDir`, not a PVC — every restart
 *      starts from genuinely nothing; see cloud/gateway/src/lib/compute.ts's
 *      `dshDeployment()`). Local/dev checkouts with no baked profile fall
 *      back to writing the manifest and running `pnpm install` inline, same
 *      as before.
 *
 *      A plain recursive copy of the baked profile is NOT enough: pnpm's
 *      `link:` protocol produces RELATIVE symlinks whose `../..` depth is
 *      computed from the on-disk nesting at install time (build-time
 *      `<dshRoot>/.profile-base/lmthing-web` vs. runtime
 *      `$DSH_HOME/profiles/lmthing-web` are different depths), so a verbatim
 *      copy produces dangling `@lmthing/dsh-*` symlinks. Fix: after copying,
 *      re-`symlink` each of `LMTHING_WEB_PROFILE_DEPS`'s entries with an
 *      ABSOLUTE target against *this boot's own* `dshRoot` — sidesteps the
 *      depth math entirely. Everything else in the hoisted `node_modules`
 *      (the transitive `@deepseek-ai/*` deps) are real files/hardlinks from
 *      pnpm's content-addressable store, unaffected by the copy.
 *   2. `$DSH_HOME/profiles/lmthing-web/cordis.patch.yml` + the
 *      `$DSH_HOME/.agent-presets/` roster — generated by
 *      `assemble-lmthing-profile.mjs`, which is safe to re-run every boot
 *      (its own header: "regenerate, don't hand-edit").
 *
 * Model routing: `@deepseek-ai/dsh-llm-pi-ai` ships mounted-but-dormant in
 * `dsh-base` (confirmed by reading its `cordis.patch.yml`: zero routes until a
 * `providers` config exists) — so pointing it at LiteLLM is a plain top-level
 * PATCH, not a new plugin insert. The gateway already injects
 * `LMTHINGCLOUD_BASE_URL`/`LMTHINGCLOUD_API_KEY` into every pod's env
 * (`cloud/gateway/src/lib/compute.ts#litellmEnvDefaults`) — `apiKeyEnv` below
 * names that variable; the secret value itself never touches a file on disk.
 * Applied as a second `--patch` layered on top of the assembled profile
 * (same mechanism `run-web.sh --real` already uses for its own overlay), so
 * it overrides the profile's keyless tracer-bullet `agent-default-model`
 * without assemble-lmthing-profile.mjs needing to know about production at
 * all.
 */
import { access, cp, mkdir, rm, symlink, writeFile } from 'node:fs/promises'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { join } from 'node:path'
import { stringify } from 'yaml'
import { LMTHING_WEB_PROFILE_DEPS, writeLmthingWebProfileManifest } from '../../../scripts/lmthing-web-profile-manifest.mjs'

const execFileAsync = promisify(execFile)

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

/**
 * @param {object} opts
 * @param {string} opts.dshRoot - the dsh workspace root baked into this image.
 * @param {string} opts.dshHome - the persistent (PVC-backed) DSH_HOME.
 * @param {string} [opts.model] - LiteLLM model id; defaults to the fleet default (LM_MODEL_M's target).
 * @param {string} [opts.userSpacesRoot] - where THING's create_agent/write_knowledge functions write
 *   new agent spaces. Only ensured to exist here — NOT yet scanned/mounted as additional presets on
 *   boot (a created space is real on disk and independently loadSpace()-able, but isn't wired as a
 *   THING delegate target or a separately reachable top-level agent yet — deliberately deferred,
 *   see dsh/PROGRESS.md's "system-thing" section for the scope boundary and why).
 */
export async function bootstrapProfile({ dshRoot, dshHome, model = 'DeepSeek-V4-Flash-0731', userSpacesRoot }) {
  if (userSpacesRoot) await mkdir(userSpacesRoot, { recursive: true })

  const profileDir = join(dshHome, 'profiles', 'lmthing-web')
  await mkdir(profileDir, { recursive: true })

  const packageJsonPath = join(profileDir, 'package.json')
  const isFreshProfile = !(await exists(packageJsonPath))
  if (isFreshProfile) {
    const bakedProfileDir = join(dshRoot, '.profile-base', 'lmthing-web')
    if (await exists(bakedProfileDir)) {
      // Fast path: the Dockerfile already ran `pnpm install` for this exact, 100%-static
      // profile at image-build time. Just copy it locally (no network) and fix up the
      // @lmthing/* symlinks pnpm's `link:` protocol wrote relative to the BUILD-time path —
      // see the module doc comment for why a verbatim copy alone leaves them dangling.
      await cp(bakedProfileDir, profileDir, { recursive: true })
      for (const [importName, dirName] of Object.entries(LMTHING_WEB_PROFILE_DEPS)) {
        const linkPath = join(profileDir, 'node_modules', ...importName.split('/'))
        await rm(linkPath, { force: true, recursive: true })
        await symlink(join(dshRoot, 'packages', dirName), linkPath, 'dir')
      }
    } else {
      // Local/dev fallback — no image-baked profile present, so write the manifest fresh and
      // actually run `pnpm install` (the one place this still happens at runtime).
      await writeLmthingWebProfileManifest({ dshRoot, profileDir })
      await execFileAsync('pnpm', ['install'], { cwd: profileDir })
    }
  }

  await execFileAsync(process.execPath, [join(dshRoot, 'scripts', 'assemble-lmthing-profile.mjs'), 'lmthing-web', dshHome], {
    cwd: dshRoot,
  })

  const patchPaths = []
  if (process.env.LMTHINGCLOUD_BASE_URL) {
    const prodPatchPath = join(dshHome, 'prod-provider.patch.yml')
    const patch = [
      {
        id: 'llm-pi-ai',
        config: {
          providers: {
            lmthingcloud: {
              baseURL: process.env.LMTHINGCLOUD_BASE_URL,
              // Confirmed live: dsh-llm-pi-ai's `api` is a closed enum —
              // "openai-completions" | "openai-responses" | "anthropic-messages"
              // — "openai" alone is rejected by cordis config validation.
              // LiteLLM's /v1 is the OpenAI Chat Completions wire shape.
              api: 'openai-completions',
              apiKeyEnv: 'LMTHINGCLOUD_API_KEY',
              models: [{ id: model }],
            },
          },
        },
      },
      { id: 'agent-default-model', config: { provider: 'lmthingcloud', model } },
    ]
    await writeFile(
      prodPatchPath,
      `# GENERATED by @lmthing/dsh-pod-server on every boot — do not hand-edit.\n\n${stringify(patch)}`,
      'utf8',
    )
    patchPaths.push(prodPatchPath)
  }

  return { profileDir, patchPaths }
}
