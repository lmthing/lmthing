#!/usr/bin/env node
/**
 * Phase 1 assembly script (see dsh/packages/README.md — this is expedient
 * scaffolding for the walking skeleton, not a formal package).
 *
 * Regenerates the `lmthing` dsh profile's cordis.patch.yml. Since the
 * architecture pivot (see the plan, "one dsh plugin per feature"), this
 * script's job shrank to two things a static YAML patch can't do any other
 * way today:
 *   1. Set THING's persona on the GLOBAL `system-prompt.persona` config —
 *      unavoidable while Phase 1 has no `dsh-agent-presets` roster (see
 *      `@lmthing/dsh-space`'s doc comment for exactly why `dsh-persona`
 *      can't be used unscoped here).
 *   2. Mount `@lmthing/dsh-space` (the umbrella plugin) with `mountPersona:
 *      false`, which itself mounts space-functions + space-delegate — no
 *      more hand-assembled function/delegate rows.
 *
 * Usage: node dsh/scripts/assemble-lmthing-profile.mjs [profileName] [dshHome]
 * profileName defaults to "lmthing" (headless); pass "lmthing-web" for the
 * web-app-bundle profile — same generated content, different front end.
 */
import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { loadSpace } from '@lmthing/dsh-space-format'
import { resolvePersonaText } from '@lmthing/dsh-space-persona'

const here = dirname(fileURLToPath(import.meta.url))
const dshDir = join(here, '..')
const systemSpacesDir = join(dshDir, 'system-spaces')
const userThingDir = join(systemSpacesDir, 'user-thing')
const systemEchoDir = join(systemSpacesDir, 'system-echo')

const profileName = process.argv[2] ?? 'lmthing'
const dshHome = process.argv[3] ?? join(dshDir, '.dsh-home')
const patchFile = join(dshHome, 'profiles', profileName, 'cordis.patch.yml')

const userThingSpace = await loadSpace(userThingDir)
const systemEchoSpace = await loadSpace(systemEchoDir)

const thing = userThingSpace.agents.thing
const echo = systemEchoSpace.agents.echo
if (!thing) throw new Error(`expected a "thing" agent in ${userThingDir}`)
if (!echo) throw new Error(`expected an "echo" agent in ${systemEchoDir}`)

const registry = {
  thing: { agent: thing, spaceDir: userThingDir },
  echo: { agent: echo, spaceDir: systemEchoDir },
}

const thingPersonaText = await resolvePersonaText(userThingDir, 'thing')

const patch = [
  // Tracer bullet (step 1) — kept so this profile stays keyless by default;
  // override with a --patch overlay for a real provider (see README).
  {
    id: 'agent-default-model',
    config: { provider: 'lmthing-mock', model: 'mock-1' },
  },
  // ENOSPC workaround (step 1) — see dsh/packages/README.md.
  { id: 'skill-filesystem', config: { watch: false } },
  { id: 'settings', config: { watch: false } },
  { id: 'credentials', config: { watch: false } },
  // THING is the sole ambient agent (no dsh-agent-presets roster yet) — set
  // its persona as the global deployment default (see @lmthing/dsh-space's
  // doc comment for exactly why this can't go through the persona plugin).
  {
    id: 'system-prompt',
    config: { persona: thingPersonaText },
  },
  {
    insert: [
      { id: 'lmthing-llm-mock', name: '@lmthing/dsh-llm-mock' },
      {
        id: 'thing-space',
        name: '@lmthing/dsh-space',
        config: { spaceDir: userThingDir, agentSlug: 'thing', registry, mountPersona: false },
      },
    ],
  },
]

const header = `# GENERATED by dsh/scripts/assemble-lmthing-profile.mjs — re-run it to regenerate.\n# Do not hand-edit; see dsh/packages/README.md for the Phase 1 walking skeleton.\n\n`
await writeFile(patchFile, header + stringify(patch), 'utf8')
console.log(`wrote ${patchFile}`)
console.log(`THING functions: ${thing.config.functions.join(', ') || '(none)'}`)
console.log(`THING delegate targets: ${Object.keys(registry).filter((slug) => slug !== 'thing').join(', ') || '(none)'}`)
