#!/usr/bin/env node
/**
 * Regenerates a dsh profile's cordis.patch.yml AND the shared `$DSH_HOME/.agent-presets/` roster
 * (Part A2 — per-agent capability isolation, see dsh/PROGRESS.md). The script's job:
 *
 *   1. Generate one `agent.cordis.yml` per agent in the registry
 *      (`@lmthing/dsh-preset-roster`) — each mounts `@lmthing/dsh-space { spaceDir, agentSlug }`
 *      with `mountPersona` at its default `true`, since a preset IS a real agent-preset scope.
 *      Written to `$DSH_HOME/.agent-presets/` — NOT a repo-tracked directory — because the `dsh`
 *      CLI's own `composeProfile` (`profile-boot-*.js`) unconditionally REPLACES an `agent-presets`
 *      row's configured `roots` with just the shipped preset root, discarding any custom `roots` a
 *      patch declares (confirmed by reading its source:
 *      `composedOverlays.push({id:'agent-presets', config:{...,roots:[{path:SHIPPED_PRESET_ROOT,
 *      ...}]}})`, unconditional once an `agent-presets` row exists at all). `$DSH_HOME/.agent-
 *      presets/` is a SEPARATE mechanism, `AgentPresets`'s own `includeUserRoot` (default `true`)
 *      — the sanctioned way to add presets when running the stock CLI. Regenerated by this script,
 *      same as `cordis.patch.yml` — the committed source of truth stays `dsh/system-spaces/*`.
 *   2. Insert `@deepseek-ai/dsh-agent-presets` (NOT mounted by either the `dsh-headless` or
 *      `dsh-web-app` bundle by default), `default: thing`.
 *   3. Insert `@lmthing/dsh-subagent-preset`'s `lmthing-subagent-preset-roster` plugin ONCE,
 *      registering one `lmthing-preset-<slug>` `SubagentProvider` per agent in the registry — see
 *      that package's doc comment for why this must be registered once, globally, not once per
 *      delegator. Needed unconditionally: `@lmthing/dsh-space-delegate` calls
 *      `ctx.agentPresets.composeFrom`/`recompose` regardless of bundle, and both throw if
 *      `agentPresets` (this row) is absent.
 *   4. TOP-LEVEL agent composition — bundle-dependent, and this is the one place headless and web
 *      profiles genuinely diverge (confirmed by reading the actual source, not assumed):
 *      - **Web bundle** (`dsh-web-app`, via its `@deepseek-ai/dsh-host-apiproxy` dependency):
 *        `dsh-host-apiproxy`'s own `composeAgent(presetId)` already calls
 *        `await presets.mount(agentCtx, resolvedId)` for every fresh top-level session when
 *        `agentPresets` is configured. So THIS SCRIPT MOUNTS NOTHING for THING at the top level —
 *        the roster's own `thing/agent.cordis.yml` (which mounts `@lmthing/dsh-space` for THING)
 *        is picked up automatically via `agent-presets.default: 'thing'`. This is what makes TRUE
 *        isolation possible: THING's own tools live in the "thing" preset's scope, a SIBLING of
 *        "echo"'s scope, not the global layer every scope inherits.
 *      - **Headless bundle** (`dsh-headless`): confirmed (grepped every installed dsh-* package)
 *        that NEITHER `dsh-headless` NOR anything it depends on ever calls
 *        `ctx.agentPresets.mount()` for a fresh top-level agent — that composition call lives
 *        ONLY in `dsh-host-apiproxy`, a `dsh-web-app`-only dependency. So a headless top-level
 *        agent is STRUCTURALLY INCAPABLE of joining a preset; this script keeps mounting
 *        `@lmthing/dsh-space` for THING directly at the top level (global scope, `mountPersona:
 *        false` + the global persona patch), EXACTLY as before Part A2. Delegation still WORKS in
 *        headless mode (recompose()-based isolation for the CHILD still runs), but isolation is
 *        NOT complete there: THING's globally-scoped tools remain visible to every scope,
 *        including a recomposed child's. This is a documented, permanent limitation of headless
 *        mode, not a bug — headless is a dev/CI convenience, never the shipped surface (Part B
 *        serves the web bundle at lmthing.chat). Verify isolation ONLY against a web-bundled
 *        profile (`lmthing-web`).
 *
 * Usage: node dsh/scripts/assemble-lmthing-profile.mjs [profileName] [dshHome]
 * profileName defaults to "lmthing" (headless); pass "lmthing-web" for the web-app-bundle profile.
 */
import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { loadSpace } from '@lmthing/dsh-space-format'
import { resolvePersonaText } from '@lmthing/dsh-space-persona'
import { generatePresetRoster } from '@lmthing/dsh-preset-roster'

const here = dirname(fileURLToPath(import.meta.url))
const dshDir = join(here, '..')
const systemSpacesDir = join(dshDir, 'system-spaces')
// The real production default agent (knowledge + functions for authoring new agent spaces — see
// dsh/PROGRESS.md, "system-thing"). `user-thing` (the Phase-1 toy trim) stays on disk only for the
// other demo profiles (assemble-tasklist-demo-profile.mjs etc.) that still reference it directly.
const systemThingDir = join(systemSpacesDir, 'system-thing')
const systemEchoDir = join(systemSpacesDir, 'system-echo')

const profileName = process.argv[2] ?? 'lmthing'
const dshHome = process.argv[3] ?? join(dshDir, '.dsh-home')
const patchFile = join(dshHome, 'profiles', profileName, 'cordis.patch.yml')
// AgentPresets' own writable/discoverable root — see the module doc comment for why this
// (not a repo-tracked directory referenced via `roots:` config) is the mechanism that works.
// Shared across every profile under this DSH_HOME, same as the shipped root is shared.
const rosterDir = join(dshHome, '.agent-presets')
// Only the web bundle's dsh-host-apiproxy auto-mounts a preset for the top-level agent — see the
// module doc comment, step 4.
const topLevelUsesPreset = profileName !== 'lmthing'

const systemThingSpace = await loadSpace(systemThingDir)
const systemEchoSpace = await loadSpace(systemEchoDir)

const thing = systemThingSpace.agents.thing
const echo = systemEchoSpace.agents.echo
if (!thing) throw new Error(`expected a "thing" agent in ${systemThingDir}`)
if (!echo) throw new Error(`expected an "echo" agent in ${systemEchoDir}`)

const registry = {
  thing: { agent: thing, spaceDir: systemThingDir },
  echo: { agent: echo, spaceDir: systemEchoDir },
}

await generatePresetRoster(
  rosterDir,
  Object.fromEntries(Object.entries(registry).map(([slug, { agent, spaceDir }]) => [slug, { spaceDir, agentSlug: agent.slug }])),
  registry,
)

const patch = [
  // Tracer bullet — kept so this profile stays keyless by default;
  // override with a --patch overlay for a real provider (see README).
  {
    id: 'agent-default-model',
    config: { provider: 'lmthing-mock', model: 'mock-1' },
  },
  // ENOSPC workaround — see dsh/packages/README.md.
  { id: 'skill-filesystem', config: { watch: false } },
  { id: 'settings', config: { watch: false } },
  { id: 'credentials', config: { watch: false } },
]

const insert = [
  { id: 'lmthing-llm-mock', name: '@lmthing/dsh-llm-mock' },
  // Part A2: the provider registrations delegation needs, regardless of bundle. MUST be inserted
  // before thing-space (headless only) mounts @lmthing/dsh-space-delegate, which references
  // lmthing-preset-<slug> provider names at apply() time — Cordis composition order in a patch's
  // insert list is the mount order.
  { id: 'lmthing-preset-providers', name: '@lmthing/dsh-subagent-preset', config: { targets: Object.keys(registry) } },
]

if (topLevelUsesPreset) {
  // Web bundle: dsh-web-app's OWN composition already `insert`s an `agent-presets` row
  // (default: standard) — a second `insert` with the same id is a hard duplicate-loader-entry
  // error (confirmed live). PATCH its existing config instead (a plain top-level {id, config}
  // entry merges into an existing row, same as agent-default-model/skill-filesystem above).
  // dsh-host-apiproxy then mounts the "thing" preset (which itself mounts @lmthing/dsh-space for
  // THING) automatically for every fresh top-level session — nothing more to insert.
  patch.push({ id: 'agent-presets', config: { default: 'thing' } })
  // Part A4: real component UI rendering — browser-only, so only the web bundle needs it. Mounted
  // once, globally (not per-agent): it renders ANY `display` call by wire tool name, regardless of
  // which agent/preset made it.
  insert.push({ id: 'lmthing-client-space-components', name: '@lmthing/dsh-client-space-components' })
  // Required, not optional (Part B, see dsh/PROGRESS.md): the web UI's own client refuses to
  // render a composable chat session with no active workspace, and picking one interactively needs
  // host.pickDirectory/listDirectory — hard-pinned to loopback, so it always 403s once dsh is
  // reached via Envoy instead of loopback. A sibling of dshHome (so /data/.dsh-home → /data/
  // workspace in production; a local repo-relative dir in dev) — a real, persistent directory the
  // agent's own file/bash tools can use, kept apart from LMTHING_USER_SPACES_ROOT's authored spaces.
  insert.push({
    id: 'lmthing-default-workspace',
    name: '@lmthing/dsh-default-workspace',
    config: { path: join(dshHome, '..', 'workspace'), title: 'LMThing' },
  })
  // LMThing branding — must be inserted AFTER the base web bundle's own
  // @deepseek-ai/dsh-client-ui-brand-official (Cordis slots are last-registration-wins for a given
  // name; confirmed live by reading that package's shipped client.js — same three slot names).
  insert.push({ id: 'lmthing-client-brand', name: '@lmthing/dsh-client-brand' })
} else {
  // Headless bundle: dsh-headless ships no agent-presets row at all (insert fresh), and no
  // auto-mount exists for the top-level agent either, so mount @lmthing/dsh-space for THING
  // directly at the top level (global scope) — same as before Part A2. Isolation is incomplete
  // here; see the module doc comment.
  insert.push({ id: 'agent-presets', name: '@deepseek-ai/dsh-agent-presets', config: { default: 'thing' } })
  insert.push({
    id: 'thing-space',
    name: '@lmthing/dsh-space',
    config: { spaceDir: systemThingDir, agentSlug: 'thing', registry, mountPersona: false },
  })
  patch.push({ id: 'system-prompt', config: { persona: await resolvePersonaText(systemThingDir, 'thing') } })
}

patch.push({ insert })

const header = `# GENERATED by dsh/scripts/assemble-lmthing-profile.mjs — re-run it to regenerate.\n# Do not hand-edit; see dsh/packages/README.md and dsh/PROGRESS.md (Part A2).\n\n`
await writeFile(patchFile, header + stringify(patch), 'utf8')
console.log(`wrote ${patchFile}`)
console.log(`wrote preset roster: ${rosterDir} (${Object.keys(registry).join(', ')})`)
console.log(`top-level preset composition: ${topLevelUsesPreset ? 'yes (web bundle — dsh-host-apiproxy auto-mounts)' : 'no (headless — see module doc comment)'}`)
console.log(`THING functions: ${thing.config.functions.join(', ') || '(none)'}`)
console.log(`THING delegate targets: ${Object.keys(registry).filter((slug) => slug !== 'thing').join(', ') || '(none)'}`)
