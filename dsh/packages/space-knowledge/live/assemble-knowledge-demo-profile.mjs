#!/usr/bin/env node
/**
 * LIVE-VERIFICATION SCAFFOLDING for `@lmthing/dsh-space-knowledge` only.
 *
 * Writes `.dsh-home/profiles/knowledge-demo/` from scratch (profile dir,
 * package.json, cordis.yml, cordis.patch.yml) so this plugin can be verified
 * against a really-booted dsh without touching any shared profile or the
 * shared `scripts/assemble-lmthing-profile.mjs`.
 *
 * Deliberately does NOT go through `@lmthing/dsh-space` (the umbrella plugin):
 * wiring this plugin into the umbrella is a separate, sequential integration
 * step owned elsewhere, so this mounts `@lmthing/dsh-space-knowledge` on its
 * own — which also proves the plugin stands alone, as every plugin in this
 * family is supposed to.
 *
 * Usage: node live/assemble-knowledge-demo-profile.mjs [agentSlug]
 *   agentSlug defaults to `librarian`; pass `intern` for the negative case
 *   (an agent that declares no knowledge: expect NO prompt section and NO
 *   loadKnowledge tool).
 *
 * Then, from dsh/:
 *   KNOWLEDGE_DEMO_DUMP=/tmp/dump.json DSH_HOME=$(pwd)/.dsh-home \
 *     npx dsh --profile knowledge-demo "hours: weekend"
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { loadSpace } from '@lmthing/dsh-space-format'

const here = dirname(fileURLToPath(import.meta.url))
const packageDir = join(here, '..')
const dshDir = join(packageDir, '..', '..')
const spaceDir = join(dshDir, 'system-spaces', 'system-knowledge-demo')

const agentSlug = process.argv[2] ?? 'librarian'
const dshHome = join(dshDir, '.dsh-home')
const profileDir = join(dshHome, 'profiles', 'knowledge-demo')

const space = await loadSpace(spaceDir)
const agent = space.agents[agentSlug]
if (!agent) throw new Error(`no "${agentSlug}" agent in ${spaceDir}`)

await mkdir(profileDir, { recursive: true })

await writeFile(join(profileDir, 'package.json'), `${JSON.stringify({
  name: 'dsh-profile-knowledge-demo',
  private: true,
  dependencies: {
    '@deepseek-ai/dsh-headless': '0.1.1-rc.2',
    '@lmthing/dsh-knowledge-demo-llm': `link:${here}`,
    '@lmthing/dsh-space-knowledge': `link:${packageDir}`,
  },
  dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless'] } },
}, null, 2)}\n`, 'utf8')

await writeFile(join(profileDir, 'cordis.yml'), '# Generated by live/assemble-knowledge-demo-profile.mjs. Edit cordis.patch.yml.\n[]\n', 'utf8')

await writeFile(join(profileDir, 'pnpm-workspace.yaml'), 'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n', 'utf8')

const patch = [
  { id: 'agent-default-model', config: { provider: 'knowledge-demo-mock', model: 'demo-1' } },
  // ENOSPC workaround — see dsh/packages/README.md.
  { id: 'skill-filesystem', config: { watch: false } },
  { id: 'settings', config: { watch: false } },
  { id: 'credentials', config: { watch: false } },
  // The agent's own persona, set the only way headless can today (no
  // dsh-agent-presets roster) — see @lmthing/dsh-space's doc comment.
  { id: 'system-prompt', config: { persona: `${agent.charterBody}\n\n${agent.instructBody}`.trim() } },
  {
    insert: [
      { id: 'knowledge-demo-llm', name: '@lmthing/dsh-knowledge-demo-llm' },
      { id: 'knowledge-demo-space-knowledge', name: '@lmthing/dsh-space-knowledge', config: { spaceDir, agentSlug } },
    ],
  },
]

const header = '# GENERATED by packages/space-knowledge/live/assemble-knowledge-demo-profile.mjs.\n# Live-verification scaffolding for @lmthing/dsh-space-knowledge; do not hand-edit.\n\n'
await writeFile(join(profileDir, 'cordis.patch.yml'), header + stringify(patch), 'utf8')

console.log(`wrote ${profileDir} for agent "${agentSlug}" (knowledge refs: ${agent.config.knowledge.join(', ') || '(none)'})`)
